"""OLT-035D: original RP2018 editor's Strong/Beta Code parsing sources.

This imports original-source word *positions* and the editor's numeric lexical
references and raw morphology, not independently verified Greek lemma forms.
Stable locators below are GENERATED BY OLT from original book/verse/ordinal;
the external BP5 text does NOT provide original canonical word token IDs.
Never infer accented Unicode Greek word surfaces from these Beta Code tokens.
"""
from __future__ import annotations

from collections import Counter
import argparse
import json
from pathlib import Path
import re
from typing import Any

from .engine import SourceContractError
from .sources import ROOT, git_blob_sha1
from .nt_corpus import read_nt_inventory, read_nt_book

MANIFEST = "data/engine/olt_035d_greek_word_source_manifest.json"
_REVISION = "27a45ff1b7be6c17ccbfeac414f3f55732ae8e28"
_SOURCE_REF = re.compile(r"^([0-9]{2})\.([0-9]{2})$")
_INTEGER = re.compile(r"^[0-9]+$")
_PARSE = re.compile(r"^\{([A-Za-z0-9-]+)\}$")


def read_word_manifest(root: Path = ROOT) -> dict[str, Any]:
    manifest = json.loads((root / MANIFEST).read_text(encoding="utf-8"))
    if (manifest.get("checkpoint"), manifest.get("upstream_tag"), manifest.get("upstream_commit"),
        manifest.get("textual_edition"), manifest.get("publication_status")) != (
        "OLT-035D", "v3.3.2", _REVISION, "ROBINSON_PIERPONT_2018", "BLOCKED"):
        raise SourceContractError("Unexpected official RP2018 source version or publication status")
    if manifest.get("full_nt_source_file_count") != 27 or len(manifest.get("files", [])) != 27:
        raise SourceContractError("All 27 original Greek source morphology books are required")
    if (manifest.get("expected_primary_word_form_records"),
        manifest.get("expected_additional_alt_parse_pairs"),
        manifest.get("expected_official_bp5_verse_lines"),
        manifest.get("expected_unicode_csv_verse_rows")) != (140149, 28, 7957, 7953):
        raise SourceContractError("Unexpected Greek source lexical/verse coverage contract")
    if (manifest.get("external_source_native_word_ids_provided") is not False or
        manifest.get("morphology_alternatives_preserved") is not True or
        manifest.get("only_verse_reference_join_to_unicode_allowed") is not True or
        manifest.get("word_lemma_forms_and_senses_certified") is not False or
        manifest.get("no_unreviewed_word_level_strong_to_unicode_alignment") is not True):
        raise SourceContractError("Original Greek word-position or philological safety contract disabled")
    if sorted(manifest.get("known_bp5_verses_absent_from_main_unicode_csv", [])) != sorted([
        "Luke.17.36", "Acts.8.37", "Acts.15.34", "Acts.24.7"
    ]):
        raise SourceContractError("Four source witness differences cannot be silently discarded")
    for i, item in enumerate(manifest["files"], 1):
        code = item.get("upstream_book_code")
        if (item.get("canonical_nt_order") != i or
            not isinstance(code, str) or
            not re.fullmatch(r"[0-9A-Z]{3}", code)):
            raise SourceContractError("Greek word-source book order or code invalid")
        filename = f"{i:02d}_{code}.BP5"
        if item.get("official_source_path") != "source/Strongs/" + filename or (
            item.get("repo_path") != "data/imported/nt/rp2018/strongs/" + filename
        ):
            raise SourceContractError("Official Greek morphology source path changed")
        if not re.fullmatch(r"[0-9a-f]{40}", item.get("official_git_blob_sha1", "")):
            raise SourceContractError("Official Greek morphology source hash missing")
        if not isinstance(item.get("byte_length"), int) or item["byte_length"] < 100:
            raise SourceContractError("Original Greek morphology source size invalid")
    if len({x["upstream_book_code"] for x in manifest["files"]}) != 27:
        raise SourceContractError("Duplicated original Greek source book")
    return manifest


def _parse_one_verse(
    original_line: str, book_id: str, source_filename: str,
    upstream_hash: str
) -> dict[str, Any]:
    """Parse source triples + optional number/morph alternative attached to last word."""
    if not isinstance(original_line, str):
        raise SourceContractError("Greek original BP5 source line must be text")
    parts = original_line.strip().split()
    if not parts:
        raise SourceContractError("Empty original Greek morphology verse")
    m = _SOURCE_REF.fullmatch(parts[0])
    if not m or not (1 <= int(m[1]) <= 50 and 1 <= int(m[2]) <= 200):
        raise SourceContractError("Malformed original Greek source chapter/verse")
    reference = f"{book_id}.{int(m[1])}.{int(m[2])}"
    tokens: list[dict[str, Any]] = []
    index = 1
    additional_analyses = 0
    while index < len(parts):
        # Official editor occasionally gives a second Strong/morph pair with
        # no second surface word. It belongs to the preceding ORIGINAL word.
        if _INTEGER.fullmatch(parts[index]):
            if not tokens or len(parts) - index < 2:
                raise SourceContractError("Unattached alternative Greek parsing/Strong number")
            parsed = _PARSE.fullmatch(parts[index + 1])
            if not parsed:
                raise SourceContractError("Malformed alternate Greek parsing code")
            tokens[-1]["additional_editor_analyses"].append({
                "strong_number": parts[index],
                "morphology_code": parsed[1],
                "source_status": "OFFICIAL_EDITOR_ALTERNATE_UNREVIEWED",
            })
            additional_analyses += 1
            index += 2
            continue
        if len(parts) - index < 3:
            raise SourceContractError("Incomplete official Greek word, Strong and morphology triple")
        form, strong, enclosed = parts[index:index + 3]
        parsed = _PARSE.fullmatch(enclosed)
        if not _INTEGER.fullmatch(strong) or not parsed or not form:
            raise SourceContractError("Malformed original Greek BP5 source word triple")
        ordinal = len(tokens) + 1
        tokens.append({
            "source_reference": reference,
            "derived_source_locator": f"rp2018-v3.3.2:{reference}:w{ordinal:04d}",
            "derived_locator_origin": "OLT_POSITION_IN_VERIFIED_OFFICIAL_BP5_NOT_NATIVE_SOURCE_WORD_ID",
            "original_source_native_word_id": None,
            "ordinal_in_source_verse": ordinal,
            "beta_code_word_form": form,
            "accented_unicode_word_form": None,
            "unicode_word_form_alignment": "NOT_PERFORMED",
            "official_editor_strong_number": strong,
            "strong_number_is_verified_dictionary_lemma": False,
            "official_editor_morphology_code": parsed[1],
            "additional_editor_analyses": [],
            "editorial_status": "IMPORTED_OFFICIAL_EDITOR_TAGS_NOT_INDEPENDENTLY_VERIFIED",
            "source_language": "grc",
            "source_file": source_filename,
            "source_git_blob_sha1": upstream_hash,
            "owner_translation": None,
            "publication_status": "BLOCKED",
        })
        index += 3
    if not tokens:
        raise SourceContractError("No original word triples in Greek source verse")
    return {
        "reference": reference,
        "source_language": "grc",
        "source_file": source_filename,
        "source_git_blob_sha1": upstream_hash,
        "source_word_count": len(tokens),
        "additional_alternative_parse_pairs": additional_analyses,
        "words": tokens,
        "translation": None,
        "independent_morphological_review": "NOT_DONE",
        "publication_status": "BLOCKED",
    }


def read_parsed_greek_book(
    code: str, root: Path = ROOT, manifest: dict[str, Any] | None = None
) -> dict[str, Any]:
    reg = manifest if manifest is not None else read_word_manifest(root)
    hits = [item for item in reg["files"] if item["upstream_book_code"] == code]
    if len(hits) != 1:
        raise SourceContractError("Unknown or ambiguous original RP2018 morphology book")
    entry = hits[0]
    path = root / entry["repo_path"]
    raw = path.read_bytes()
    if len(raw) != entry["byte_length"] or git_blob_sha1(raw) != entry["official_git_blob_sha1"]:
        raise SourceContractError("Official RP2018 Strongs/BP5 file differs from pinned editor's Git blob")
    original = raw.decode("ascii", errors="strict")
    lines = [x for x in original.splitlines() if x.strip()]
    if len(lines) != entry["expected_source_verse_lines"]:
        raise SourceContractError("Greek original parsed source verse total changed")
    verses = [
        _parse_one_verse(x, entry["canonical_book_id"], entry["official_source_path"],
                         entry["official_git_blob_sha1"])
        for x in lines
    ]
    refs = [v["reference"] for v in verses]
    if len(refs) != len(set(refs)):
        raise SourceContractError("Greek original source verse references duplicated")
    count = sum(v["source_word_count"] for v in verses)
    alt = sum(v["additional_alternative_parse_pairs"] for v in verses)
    if (count, alt) != (
        entry["expected_primary_form_strongs_parsing_pairs"],
        entry["expected_additional_alternative_strongs_parsing_pairs"]
    ):
        raise SourceContractError("Greek official original word or alternate morphology count changed")
    return {
        "book_code": code,
        "book_id": entry["canonical_book_id"],
        "source_file": entry["official_source_path"],
        "source_git_blob_sha1": entry["official_git_blob_sha1"],
        "source_edition": "RP2018_BYZTXT_v3.3.2",
        "verse_count": len(verses),
        "primary_word_forms": count,
        "additional_alternative_parse_pairs": alt,
        "verse_records": verses,
        "word_position_ids_are_editor_original": False,
        "morphology_approved_by_independent_scholars": False,
        "lexical_lemmas_approved": False,
        "publication_status": "BLOCKED",
    }


def verify_greek_words(root: Path = ROOT) -> dict[str, Any]:
    reg = read_word_manifest(root)
    verses_source = read_nt_inventory(root)
    if reg["unicode_verse_reference_inventory"] != (
        "data/engine/olt_035b_rp2018_verse_inventory.json"
    ):
        raise SourceContractError("Unsafe or incorrect Greek Unicode source join reference")
    if [x["upstream_book_code"] for x in reg["files"]] != [
        x["upstream_book_code"] for x in verses_source["continuous_books"]
    ]:
        raise SourceContractError("Original morphology book ordering does not match pinned Greek verse source")
    counters: Counter[str] = Counter()
    original_extras: set[str] = set()
    all_derived = set()
    per_book = []
    for spec in reg["files"]:
        code = spec["upstream_book_code"]
        source = read_parsed_greek_book(code, root, reg)
        unicode_verses = read_nt_book(code, root, verses_source)
        original_refs = {v["reference"] for v in source["verse_records"]}
        unicode_refs = {v["reference"] for v in unicode_verses["verses"]}
        if unicode_refs - original_refs:
            raise SourceContractError("Greek Unicode verse is absent in official Strong morphology source")
        original_extras.update(original_refs - unicode_refs)
        counters["bp5_verses"] += source["verse_count"]
        counters["unicode_verses"] += unicode_verses["verse_count"]
        counters["primary_word_forms"] += source["primary_word_forms"]
        counters["alternative_parse_pairs"] += source["additional_alternative_parse_pairs"]
        for verse in source["verse_records"]:
            for word in verse["words"]:
                identifier = word["derived_source_locator"]
                if identifier in all_derived:
                    raise SourceContractError("Nonunique generated original-position locator")
                all_derived.add(identifier)
                if word["source_language"] != "grc" or word["owner_translation"] is not None:
                    raise SourceContractError("Original Greek imported source cannot already be translated")
        per_book.append({
            "book": source["book_id"],
            "bp5_verse_lines": source["verse_count"],
            "unicode_csv_verse_rows": unicode_verses["verse_count"],
            "original_bp5_source_word_forms": source["primary_word_forms"],
            "alternative_analyses": source["additional_alternative_parse_pairs"],
        })
    if original_extras != set(reg["known_bp5_verses_absent_from_main_unicode_csv"]):
        raise SourceContractError("Known BP5/CCAT Unicode source verse differences changed")
    if (counters["bp5_verses"], counters["unicode_verses"],
        counters["primary_word_forms"], counters["alternative_parse_pairs"]) != (
        reg["expected_official_bp5_verse_lines"],
        reg["expected_unicode_csv_verse_rows"],
        reg["expected_primary_word_form_records"],
        reg["expected_additional_alt_parse_pairs"]
    ):
        raise SourceContractError("Complete Greek original word and verse source totals changed")
    return {
        "checkpoint": "OLT-035D",
        "upstream_commit": reg["upstream_commit"],
        "official_source_books": 27,
        "official_beta_strongs_verses": counters["bp5_verses"],
        "matching_unicode_verse_rows": counters["unicode_verses"],
        "editor_source_word_form_records": counters["primary_word_forms"],
        "extra_alternative_parse_pairs_attached_to_words": counters["alternative_parse_pairs"],
        "official_bp5_only_verse_refs_require_textual_review": sorted(original_extras),
        "per_book": per_book,
        "unique_position_locators": len(all_derived),
        "locators_are_native_publisher_ids": False,
        "accented_greek_unicode_word_join_complete": False,
        "strong_numbers_mean_independently_verified_lemmas": False,
        "independent_morphology_review": "NOT_DONE",
        "english_master_lexicon_status": "NOT_COMPLETE",
        "target_locale_translations": "NOT_DONE",
        "publication_status": "BLOCKED",
    }


def main() -> int:
    parser = argparse.ArgumentParser(description="OLT-035D official RP2018 Greek word-source read-only audit")
    choice = parser.add_mutually_exclusive_group(required=True)
    choice.add_argument("--audit", action="store_true")
    choice.add_argument("--verse", nargs=2, metavar=("SOURCE_BOOK_CODE", "REFERENCE"))
    args = parser.parse_args()
    if args.audit:
        result = verify_greek_words()
    else:
        code, verse_ref = args.verse
        book = read_parsed_greek_book(code)
        found = [v for v in book["verse_records"] if v["reference"] == verse_ref]
        if len(found) != 1:
            raise SystemExit("No matching pinned official Greek source verse")
        result = found[0]
    print(json.dumps(result, ensure_ascii=False, sort_keys=True, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
