"""CHES-008/009/010: private English source-draft batch for four, six or bounded index-pinned PDFs.

Four sources remain the stable default; --extended selects six, --indexed adds registry pins. Each completed
chapter is stored as private 0600 JSON and checkpointed with its output SHA-256.
Re-runs skip verified outputs; an interrupted write (output but no checkpoint)
is recovered ONLY if newly generated bytes exactly match the orphan.

All English fragments are licensed private CHES source glosses, NOT completed
English OLT translations. No copyrighted content is emitted to stdout/CI.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
from typing import Any

from olt_core.sources import ROOT, load_ot_book, read_provenance
from scripts.ches_import import import_private_pdf, write_private_json
from scripts.ches_lite_english import build_private_genesis_one_english_drafts
from scripts.ches_007_multichapter_english import build_private_english_from_original_pdf
from scripts.ches_private_alignment_review import private_file
from scripts.ches_010_pin_registry import INDEXED_BATCH_ITEMS, pinned_record

BATCH = (
    ("Gen", 1, "ches-gen1.pdf", "source_reference"),
    ("Gen", 2, "ches-gen2.pdf", "additional_chapter_layout_source_reference"),
    ("Gen", 3, "ches-gen3.pdf", "third_chapter_layout_source_reference"),
    ("Exod", 1, "ches-ex1.pdf", "cross_book_layout_source_reference"),
)
# CHES-009 is opt-in, to preserve byte-for-byte compatibility with existing
# four-chapter output checkpoints and the original CHES-008 default behavior.
EXTENDED_BATCH = BATCH + (
    ("Gen", 4, "ches-gen4.pdf", "fifth_chapter_layout_source_reference"),
    ("Exod", 2, "ches-ex2.pdf", "sixth_chapter_layout_source_reference"),
)
INDEXED_BATCH = EXTENDED_BATCH + INDEXED_BATCH_ITEMS
CHECKPOINT = "CHES-008"
STATE_FILE = "ches-008-state.json"
VALID_STATE_KEYS = frozenset({"checkpoint", "publication_status", "chapters", "failures"})
OUTPUT_SUFFIX = "-private-english-working.json"


class CHESBatchError(ValueError):
    """Failed original-source integrity, private checkpoint or chapter generation."""


def _canonical_bytes(obj: dict[str, Any]) -> bytes:
    return (json.dumps(obj, ensure_ascii=False, sort_keys=True, indent=2) + "\n").encode("utf-8")


def _source_pin(root: Path, pin_key: str, book: str, chapter: int) -> dict[str, Any]:
    manifest = json.loads(
        (root / "data/engine/olt_ches_source_manifest.json").read_text(encoding="utf-8")
    )
    pin = (pinned_record(book, chapter, root)
           if pin_key == "indexed_original_source_pins"
           else manifest.get(pin_key))
    if (not isinstance(pin, dict) or pin.get("original_book") != book
        or type(pin.get("original_chapter")) is not int or pin["original_chapter"] != chapter
        or type(pin.get("source_pdf_bytes")) is not int
        or not isinstance(pin.get("source_pdf_sha256"), str)
        or len(pin["source_pdf_sha256"]) != 64
        or type(pin.get("printed_pdf_verses_confirmed_by_engineering")) is not int
        or type(pin.get("green_ches_pdf_spans_extracted")) is not int
        or pin.get("source_pdf_stored_in_public_repo", False) is not False
        or pin.get("word_and_morpheme_alignment_verified", False) is not False):
        raise CHESBatchError("Source provenance/rights pin invalid")
    return pin


def _verified_pdf(folder: Path, filename: str, pin: dict[str, Any]) -> bytes:
    """No network; local original PDF bytes are mandatory even on a skipped run."""
    path = folder / filename
    if not path.is_file() or path.is_symlink():
        raise CHESBatchError("MISSING_OR_UNSAFE_SOURCE_PDF")
    if path.stat().st_size != pin["source_pdf_bytes"]:
        raise CHESBatchError("SOURCE_PDF_SIZE_MISMATCH")
    data = path.read_bytes()
    if (not data.startswith(b"%PDF-") or len(data) != pin["source_pdf_bytes"]
        or hashlib.sha256(data).hexdigest() != pin["source_pdf_sha256"]):
        raise CHESBatchError("SOURCE_PDF_SHA256_MISMATCH")
    return data


def _generate(book: str, chapter: int, pdf_data: bytes, root: Path) -> dict[str, Any]:
    if (book, chapter) == ("Gen", 1):
        source = import_private_pdf(pdf_data, "Gen", 1, expected_verses=31)
        return build_private_genesis_one_english_drafts(source, root=root)
    return build_private_english_from_original_pdf(
        pdf_data, book=book, chapter=chapter, root=root
    )


def _report_contract(
    result: dict[str, Any], *,
    book: str, chapter: int, pin: dict[str, Any], root: Path,
) -> dict[str, int]:
    """Reject false approval and verify every original Hebrew token ID."""
    expected_verses = pin["printed_pdf_verses_confirmed_by_engineering"]
    expected_span_count = pin["green_ches_pdf_spans_extracted"]
    source_id = f"{book}.{chapter}"
    if (not isinstance(result, dict) or
        result.get("checkpoint") != ("CHES-004" if chapter == 1 and book == "Gen"
                                    else "CHES-007") or
        result.get("scope") not in ({source_id + "_ONLY"} if source_id == "Gen.1"
                                    else {source_id}) or
        result.get("source_pdf_sha256") != pin["source_pdf_sha256"] or
        result.get("original_ches_pdf_green_span_count") != expected_span_count or
        result.get("publication_status") != "BLOCKED" or
        result.get("english_language_only") is not True or
        result.get("private_copyrighted_source_text") is not True or
        result.get("english_translation_owner_approved") is not False or
        result.get("complete_english_bible_owner_approved") is not False or
        result.get("word_alignment_verified") is not False or
        result.get("all_english_grammar_rules_applied") is not False or
        result.get("old_full_lexical_engine_required") is not False or
        result.get("private_editorial_verse_edits_unapproved") != 0):
        raise CHESBatchError("UNSAFE_PRIVATE_ENGLISH_DRAFT")
    rows = result.get("verses")
    if not isinstance(rows, list) or len(rows) != expected_verses:
        raise CHESBatchError("PRIVATE_ENGLISH_VERSE_INVENTORY_MISMATCH")
    if (result.get("genesis_verse_count") if source_id == "Gen.1"
        else result.get("verse_count")) != expected_verses:
        raise CHESBatchError("PRIVATE_ENGLISH_VERSE_COUNT_MISMATCH")
    original = load_ot_book(book, root, read_provenance(root))
    actual = {
        verse["reference"]: verse["words"] for verse in original["verses"]
        if verse["reference"].startswith(source_id + ".")
    }
    if len(actual) != expected_verses:
        raise CHESBatchError("PINNED_ORIGINAL_HEBREW_VERSE_COUNT_MISMATCH")
    words = spans = simple_past = lexical_candidates = 0
    for ordinal, row in enumerate(rows, 1):
        ref = f"{source_id}.{ordinal}"
        if not isinstance(row, dict) or row.get("reference") != ref:
            raise CHESBatchError("PRIVATE_ENGLISH_SOURCE_VERSE_ID_MISMATCH")
        original_ids = [w["source_id"] for w in actual[ref]]
        if (row.get("original_source_word_token_ids") != original_ids or
            row.get("original_source_word_count") != len(original_ids) or
            row.get("publication_status") != "BLOCKED" or
            row.get("english_owner_approved") is not False or
            row.get("all_source_grammar_rules_applied") is not False or
            row.get("english_draft_status") != "UNREVIEWED_PRIVATE_ENGLISH_WORKING_DRAFT" or
            row.get("english_text_origin") !=
                "MECHANICAL_CHES_SOURCE_GLOSS_STREAM_NOT_OLT_TRANSLATION" or
            row.get("editorial_evidence_note_private") is not None or
            row.get("english_text_private_unapproved") !=
                row.get("ches_raw_gloss_stream_private_unapproved") or
            not isinstance(row.get("english_text_private_unapproved"), str) or
            not row["english_text_private_unapproved"]):
            raise CHESBatchError("PRIVATE_ENGLISH_VERSE_APPROVAL_OR_SOURCE_MISMATCH")
        if (source_id == "Gen.1" and row.get("word_alignment_verified") is not False or
            source_id != "Gen.1" and
            row.get("oshb_to_ches_word_alignment_verified") is not False):
            raise CHESBatchError("PRIVATE_WORD_ALIGNMENT_FALSE_CERTIFICATION")
        count = row.get("private_original_ches_green_span_count")
        tense = row.get("source_tagged_wayyiqtol_requirements")
        lex = row.get("original_source_lexical_override_candidates")
        if (type(count) is not int or count < 1 or
            not isinstance(tense, list) or not isinstance(lex, list)):
            raise CHESBatchError("PRIVATE_ORIGINAL_SOURCE_TOKEN_COUNT_INVALID")
        # Per-token candidate IDs may only be real words in this exact verse.
        for candidate in tense + lex:
            if (not isinstance(candidate, dict)
                or candidate.get("original_token_id") not in original_ids):
                raise CHESBatchError("PRIVATE_RULE_REFERENCES_UNKNOWN_ORIGINAL_WORD")
        words += len(original_ids)
        spans += count
        simple_past += len(tense)
        lexical_candidates += len(lex)
    if (spans != expected_span_count or
        result.get("original_hebrew_token_count") != words or
        result.get("source_wayyiqtol_simple_past_requirements") != simple_past or
        result.get("owner_lexical_override_candidates_not_applied") != lexical_candidates):
        raise CHESBatchError("PRIVATE_ORIGINAL_SOURCE_COUNTS_CHANGED")
    return {"verses": expected_verses, "hebrew_tokens": words,
            "pdf_spans": spans, "wayyiqtol_requirements": simple_past,
            "lexical_candidates": lexical_candidates}


def _state(outdir: Path) -> dict[str, Any]:
    file = outdir / STATE_FILE
    if not file.exists():
        return {"checkpoint": CHECKPOINT, "publication_status": "BLOCKED",
                "chapters": {}, "failures": {}}
    if file.is_symlink():
        raise CHESBatchError("PRIVATE_BATCH_STATE_IS_SYMLINK")
    try:
        data = json.loads(file.read_text(encoding="utf-8"))
    except (ValueError, UnicodeError, OSError) as exc:
        raise CHESBatchError("PRIVATE_BATCH_STATE_CORRUPT") from exc
    valid_ids = {f"{b}.{c}" for b, c, _, _ in INDEXED_BATCH}
    if (not isinstance(data, dict) or set(data) != VALID_STATE_KEYS or
        data["checkpoint"] != CHECKPOINT or data["publication_status"] != "BLOCKED" or
        not isinstance(data["chapters"], dict) or
        not isinstance(data["failures"], dict) or
        not set(data["chapters"]).issubset(valid_ids) or
        not set(data["failures"]).issubset(valid_ids) or
        any(not isinstance(v, dict) for v in data["chapters"].values())):
        raise CHESBatchError("PRIVATE_BATCH_STATE_UNTRUSTED")
    return data


def _output_name(book: str, chapter: int) -> str:
    return f"{book.lower()}-{chapter}" + OUTPUT_SUFFIX


def _record(
    report: dict[str, Any], *,
    book: str, chapter: int, pin: dict[str, Any], root: Path,
) -> dict[str, Any]:
    measurements = _report_contract(report, book=book, chapter=chapter, pin=pin, root=root)
    return {
        "status": "COMPLETE_PRIVATE_UNAPPROVED",
        "original_pdf_sha256": pin["source_pdf_sha256"],
        "output_sha256": hashlib.sha256(_canonical_bytes(report)).hexdigest(),
        "publication_status": "BLOCKED",
        **measurements,
    }


def _verify_saved_output(
    path: Path, prior: dict[str, Any], *,
    book: str, chapter: int, pin: dict[str, Any], root: Path,
) -> None:
    """Never overwrite private data that was edited, corrupted or replaced."""
    if not path.is_file() or path.is_symlink():
        raise CHESBatchError("PRIVATE_DRAFT_MISSING_OR_SYMLINK")
    try:
        raw = path.read_bytes()
        report = json.loads(raw)
        measured = _record(report, book=book, chapter=chapter, pin=pin, root=root)
    except (OSError, UnicodeError, ValueError, KeyError, TypeError) as err:
        raise CHESBatchError("PRIVATE_DRAFT_UNVERIFIED") from err
    if raw != _canonical_bytes(report) or measured != prior:
        raise CHESBatchError("PRIVATE_DRAFT_CHANGED_DO_NOT_OVERWRITE")


def run_private_chapter_batch(
    pdf_directory: Path, private_output_directory: Path, *,
    root: Path = ROOT, limit: int | None = None,
    extended: bool = False, indexed: bool = False,
) -> dict[str, Any]:
    """Resume exact four/six-chapter work in stable order, preserving earlier output.

    The private state is updated after each chapter success or failure.
    No source text, edit note, private path or English verse is returned.
    """
    if type(extended) is not bool or type(indexed) is not bool or (extended and indexed):
        raise CHESBatchError("Invalid or conflicting batch scope")
    selected = INDEXED_BATCH if indexed else EXTENDED_BATCH if extended else BATCH
    if limit is None:
        limit = len(selected)
    if type(limit) is not int or not 1 <= limit <= len(selected):
        raise CHESBatchError("Chapter batch bound exceeds selected source-pinned scope")
    if not isinstance(pdf_directory, Path) or not pdf_directory.is_dir():
        raise CHESBatchError("Original PDF source directory is absent")
    output = private_file(private_output_directory / STATE_FILE).parent
    output.mkdir(mode=0o700, parents=True, exist_ok=True)
    state = _state(output)
    counters = {"built": 0, "skipped": 0, "recovered": 0, "failed": 0}
    for book, chapter, filename, key in selected[:limit]:
        scope = f"{book}.{chapter}"
        destination = output / _output_name(book, chapter)
        try:
            pin = _source_pin(root, key, book, chapter)
            original_pdf = _verified_pdf(pdf_directory, filename, pin)
            if scope in state["chapters"]:
                _verify_saved_output(
                    destination, state["chapters"][scope], book=book, chapter=chapter,
                    pin=pin, root=root
                )
                state["failures"].pop(scope, None)
                counters["skipped"] += 1
            elif destination.exists() or destination.is_symlink():
                # An interrupted write may have left an output before its
                # checkpoint. Verify exact re-created source-derived bytes
                # before adopting. Never quietly absorb an edited orphan.
                regenerated = _generate(book, chapter, original_pdf, root)
                expected = _record(regenerated, book=book, chapter=chapter, pin=pin, root=root)
                _verify_saved_output(
                    destination, expected, book=book, chapter=chapter, pin=pin, root=root
                )
                state["chapters"][scope] = expected
                state["failures"].pop(scope, None)
                counters["recovered"] += 1
            else:
                generated = _generate(book, chapter, original_pdf, root)
                record = _record(generated, book=book, chapter=chapter, pin=pin, root=root)
                write_private_json(generated, destination)
                _verify_saved_output(
                    destination, record, book=book, chapter=chapter, pin=pin, root=root
                )
                state["chapters"][scope] = record
                state["failures"].pop(scope, None)
                counters["built"] += 1
        except Exception as exc:
            # The failed chapter stays retryable. Only allowlisted metadata
            # leaves the function; never print exception arguments/raw CHES text.
            state["failures"][scope] = {
                "status": "FAILED_RETRYABLE",
                "failure_code": (
                    str(exc) if isinstance(exc, CHESBatchError)
                    and str(exc) in {
                        "MISSING_OR_UNSAFE_SOURCE_PDF", "SOURCE_PDF_SIZE_MISMATCH",
                        "SOURCE_PDF_SHA256_MISMATCH", "PRIVATE_DRAFT_MISSING_OR_SYMLINK",
                        "PRIVATE_DRAFT_UNVERIFIED", "PRIVATE_DRAFT_CHANGED_DO_NOT_OVERWRITE"
                    } else "SOURCE_OR_GENERATION_VERIFICATION_FAILED"
                ),
            }
            counters["failed"] += 1
        write_private_json(state, output / STATE_FILE)
    # In a limited run, chapter keys beyond the limit remain untouched.
    records = state["chapters"]
    active_ids = {f"{book}.{chapter}" for book, chapter, _, _ in selected}
    completed_ids = set(records).intersection(active_ids)
    active_failures = {
        k: v for k, v in state["failures"].items() if k in active_ids
    }
    return {
        "checkpoint": CHECKPOINT,
        "attempted_chapters": limit,
        "completed_chapters_stored_private": len(completed_ids),
        "total_supported_pinned_chapters": len(selected),
        "complete": completed_ids == active_ids and not active_failures,
        **counters,
        "failed_chapter_codes": [
            {"scope": scope, "code": value["failure_code"]}
            for scope, value in sorted(active_failures.items())
        ],
        "source_word_to_english_gloss_alignment_verified": False,
        "english_translation_owner_approved": False,
        "publication_status": "BLOCKED",
    }


def main() -> int:
    p = argparse.ArgumentParser(description="Four, six or index-pinned OT PDFs -> resumable PRIVATE English gloss drafts")
    p.add_argument("--pdf-directory", type=Path, required=True)
    p.add_argument("--output-private-directory", type=Path, required=True)
    p.add_argument("--confirm-machine-readable-use-permission", action="store_true")
    scope = p.add_mutually_exclusive_group()
    scope.add_argument("--extended", action="store_true",
                       help="Opt into original six source-pinned PDFs")
    scope.add_argument("--indexed", action="store_true",
                       help="Opt into all registry-pinned original chapter PDFs")
    p.add_argument("--limit", type=int, choices=range(1, 17))
    args = p.parse_args()
    if not args.confirm_machine_readable_use_permission:
        p.error("Owner-confirmed original machine-readable private use permission required")
    result = run_private_chapter_batch(
        args.pdf_directory, args.output_private_directory,
        limit=args.limit, extended=args.extended, indexed=args.indexed
    )
    print(json.dumps(result, sort_keys=True, indent=2))
    return int(bool(result["failed"]))


if __name__ == "__main__":
    raise SystemExit(main())
